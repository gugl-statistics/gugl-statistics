# Usage: python3 gen_data.py <folder with the NLTK Gutenberg .txt files>
import sys, json, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hw2 import Model, letters
F = (sys.argv[1] if len(sys.argv) > 1 else "gutenberg").rstrip("/") + "/"
train = ["austen-emma.txt","austen-persuasion.txt","austen-sense.txt","chesterton-ball.txt",
         "chesterton-brown.txt","chesterton-thursday.txt","melville-moby_dick.txt","edgeworth-parents.txt"]
M = Model("".join(open(F+f, encoding="latin-1").read() for f in train))
A="ABCDEFGHIJKLMNOPQRSTUVWXYZ"
bi=[[round(M.bi[a+b],3) for b in A] for a in A]
alice=letters(open(F+"carroll-alice.txt",encoding="latin-1").read())
start=alice.find("ALICEWASBEGINNING")
test=alice[start:start+40000]
res={"lengths":[5,10,15,20,25,30,40,50,75,100,200,500],
 "mostfreq":[13.8,23.6,28.6,30.9,33.6,36.5,40.9,48.7,50.8,57.5,71.1,85.6],
 "chi2":[48.7,75.6,88.6,93.7,95.9,98.0,99.1,99.2,100,100,100,100],
 "bigram":[74.7,97.5,99.8,100,100,100,100,100,100,100,100,100],
 "quadgram":[87.8,99.5,99.9,100,100,100,100,100,100,100,100,100]}
out="// Generated by code/gen_data.py from the training corpus (8 public-domain Gutenberg books, %d letters).\n"%M.n_letters
out+="const CORPUS_LETTERS=%d;\n"%M.n_letters
out+="const EN_FREQ="+json.dumps([round(p,5) for p in M.uni])+";\n"
out+="const BIGRAM_LOG="+json.dumps(bi,separators=(',',':'))+";\n"
out+="// Held-out test text: 'Alice in Wonderland' (Carroll), letters only, never used for training.\n"
out+="const TEST_TEXT=\""+test+"\";\n"
out+="const PY_RESULTS="+json.dumps(res)+";\n"
open(os.path.join(os.path.dirname(__file__), "..", "js", "data.js"),"w").write(out)
print(len(out), test[:80])
